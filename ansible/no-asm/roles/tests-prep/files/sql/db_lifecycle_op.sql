WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK;
WHENEVER OSERROR EXIT FAILURE ROLLBACK;
SET SQLBLANKLINES ON VERIFY OFF FEEDBACK OFF HEADING OFF PAGESIZE 0 LINESIZE 300 TRIMSPOOL ON

DECLARE
    v_op VARCHAR2(50 BYTE) := UPPER('&1');
BEGIN
    CASE v_op
        WHEN 'CHECKPOINT' THEN
            EXECUTE IMMEDIATE 'ALTER SYSTEM CHECKPOINT';
        WHEN 'ARCHIVE_LOG_CURRENT' THEN
            EXECUTE IMMEDIATE 'ALTER SYSTEM ARCHIVE LOG CURRENT';
        WHEN 'BEGIN_BACKUP' THEN
            EXECUTE IMMEDIATE 'ALTER DATABASE BEGIN BACKUP';
        WHEN 'END_BACKUP' THEN
            EXECUTE IMMEDIATE 'ALTER DATABASE END BACKUP';
            EXECUTE IMMEDIATE 'ALTER SYSTEM ARCHIVE LOG CURRENT';
        ELSE
            raise_application_error(-20002, 'Unsupported database lifecycle operation: ' || v_op);
    END CASE;
END;
/

SELECT 'OP_OK|' || UPPER('&1') FROM dual;

EXIT SUCCESS;
