WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK;
WHENEVER OSERROR EXIT FAILURE ROLLBACK;
SET SQLBLANKLINES ON VERIFY OFF FEEDBACK OFF HEADING OFF PAGESIZE 0 LINESIZE 300 TRIMSPOOL ON

SELECT 'TOPO_CHECK|' || p.open_mode || '|' || COUNT(d.file#)
  FROM v$pdbs p
  LEFT JOIN v$datafile d
    ON p.con_id = d.con_id
   AND d.name LIKE '&2/%'
 WHERE p.name = UPPER('&1')
 GROUP BY p.open_mode;

EXIT SUCCESS;
